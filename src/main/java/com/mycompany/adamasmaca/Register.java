    private void logYaz(String durumMesaji){
        
        try{
            DateTimeFormatter dtf = DateTimeFormatter.ofPattern("dd.MM.yyyy HH:mm:ss");
            LocalDateTime simdi = LocalDateTime.now();
            String zamanFormatli = dtf.format(simdi);
            
            FileWriter writer = new FileWriter(logData, true);
            writer.write(durumMesaji + " " +zamanFormatli + "\n");
            writer.close();
            
            
            
        }catch(IOException e){
            System.out.println("Log dosyasına yazılamadı: " + e.getMessage());
        }
        
        
    }
    
    
    
    

