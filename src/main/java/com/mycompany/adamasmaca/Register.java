    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String sifre = textField1.getText();
        
        if(sifre.isEmpty()){
            
            logYaz("Şifre_alanı_boş.");
            
            JOptionPane.showMessageDialog(this, "Lütfen bir sifre giriniz.","Uyarı",JOptionPane.WARNING_MESSAGE);
            
            
        }else{
            try{
                BufferedReader reader = new BufferedReader(new FileReader(rgsData));
                
                String kayitliSifre = reader.readLine();
                reader.close();
                
                if(sifre.equals(kayitliSifre)){
                    
                    logYaz("giriş_yapıldı");
                    
                    JOptionPane.showMessageDialog(this, "Giriş başarılı! Oyun açılıyor...", "Başarılı", JOptionPane.INFORMATION_MESSAGE);
                    
                    
                    
                    //Giriş yapıldıktan sonra GUI'a yönlendirilecek.
                    
                    new GUI().setVisible(true);
                    
                    this.dispose();
                }else{
                    logYaz("Yanlış_giriş_denemesi");
                    girisDenemesi--;
                    if(girisDenemesi > 0){
                        JOptionPane.showMessageDialog(this, "Yanlış bir sifre girdiniz."+ girisDenemesi +" Deneme hakkınız kaldı.","Uyarı",JOptionPane.WARNING_MESSAGE);
                    }else{
                        JOptionPane.showMessageDialog(this, "3 kez hatalı giriş yaptınız. Program kapatılıyor...","Hata",JOptionPane.ERROR_MESSAGE);
                        System.exit(0);
                    }
                }
                
                
            }catch(IOException e){
                JOptionPane.showMessageDialog(this, "Şifre kontrol edilirken bir hata oluştu!" + e.getMessage(), "Hata", JOptionPane.ERROR_MESSAGE);
            }
        }
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String sifre = textField1.getText();
        if(sifre.isEmpty()){
            logYaz("Şifre_alanı_boş");
            JOptionPane.showMessageDialog(this, "Lütfen bir sifre giriniz.","Uyarı",JOptionPane.WARNING_MESSAGE);
        }else{
            try{
                FileWriter writer = new FileWriter(rgsData);
                writer.write(sifre);
                writer.close();
                logYaz("Başarılı_şifre_kayıt.");
                
                
                
                //Giriş yapıldıktan sonra GUI'a gönderilecek.
                new GUI().setVisible(true);
                
                this.dispose();
                
            }catch(IOException e){
                JOptionPane.showMessageDialog(this,"Şifre kaydedilirken bir hata oluştu!" + e.getMessage(),"Hata",JOptionPane.ERROR_MESSAGE);
            }
        }
        
    }//GEN-LAST:event_jButton2ActionPerformed

