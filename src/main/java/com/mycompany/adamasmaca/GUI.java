    private void sonucYaz(int puan,int saniye,String kazanmaDurumu){
        
        try{
            
            DateTimeFormatter dtf = DateTimeFormatter.ofPattern("dd.MM.yyyy HH:mm:ss");
            LocalDateTime simdi = LocalDateTime.now();
            String zamanFormatli = dtf.format(simdi);
            
            FileWriter writer = new FileWriter(gameData, true);
            
            writer.write(String.valueOf(puan) + " " + String.valueOf(saniye) + " " + kazanmaDurumu + " " + zamanFormatli + "\n");
            writer.close();
            
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Oyununuzun sonucu kayıt alınırken bir hata oldu! " + e.getMessage(), "Hata", JOptionPane.ERROR_MESSAGE);
        }
        
        
        
    }
    
    private void eskiSkorlar(){
        try{
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            
            model.setRowCount(0);
            
            if(!gameData.exists()){
                return;
            }
            
            BufferedReader reader = new BufferedReader(new FileReader(gameData));
            
            String satir;
            
            while((satir = reader.readLine()) != null){
                if(!satir.trim().isEmpty()){
                    String[] sutunVerileri = satir.split(" ");
                    
                    model.addRow(sutunVerileri);
                }
            }
            reader.close();
            
        }catch(IOException e){
            System.out.println("skorlar goruntulenirken sorun oluştu!" + e.getMessage());
        }
    }
