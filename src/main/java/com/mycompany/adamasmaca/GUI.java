    private String randomWordsChoose(){
        ArrayList<String> kelimeListesi = new ArrayList<>();
        String secilenKelime= "";
        
        try{
            BufferedReader reader = new BufferedReader(new FileReader(wordsData));
            String satir;
            
            while((satir = reader.readLine()) != null){
                
                if(!satir.trim().isEmpty()){
                    kelimeListesi.add(satir.trim().toUpperCase());
                }
            }
            reader.close();
            
            if(kelimeListesi.size() > 0){
                Random rnd = new Random();
                
                int rndIndex = rnd.nextInt(kelimeListesi.size());
                
                secilenKelime = kelimeListesi.get(rndIndex);
                
            }else{
                JOptionPane.showMessageDialog(this,"kelimeler.txt dosyası boş!", "Hata", JOptionPane.ERROR_MESSAGE);
            }
            
            
            
            
        }catch(IOException e){
            JOptionPane.showMessageDialog(this,"kelimeler okunurken bir hata oldu!" + e.getMessage(), "Hata", JOptionPane.ERROR_MESSAGE);
        }
        
        
        return secilenKelime;
    }
    
