    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String harf = jTextField2.getText().toUpperCase();
        String kelime = jTextField1.getText().toUpperCase();
        
        if(!harf.isEmpty()){
            dogruTahmin = false;
            char girilenHarf = harf.charAt(0);
            
            
            for(int i = 0; i < hedefKelime.length(); i++){
                
                if(hedefKelime.charAt(i) == girilenHarf){
                    JLabel ilgiliEtiket = (JLabel) jPanel4.getComponent(i);
                    
                    ilgiliEtiket.setText(String.valueOf(girilenHarf));
                    
                    dogruTahmin = true;
                    score += 5;
                    
                }
                
                
            }
            if(dogruTahmin){
                
                jTextField2.setText("");
                //kazanma durumunu kontrol et.(tüm yıldızlar açıldı mı?)
                for(int j = 0; j < hedefKelime.length(); j++ ){
                    JLabel etiket = (JLabel) jPanel4.getComponent(j);
                    if(!etiket.getText().equals("*")){
                        
                        acikHarfSayisi++;
                    }
                }
                if(hedefKelime.length() ==acikHarfSayisi){
                    //kazanma durumunda yapılanlar.
                    kronometre.stop();
                    sonucYaz(score, gecenSaniye, "Kazanıldı");
                    JOptionPane.showMessageDialog(this,"Kazandınız!");
                    eskiSkorlar();
                }else{
                    acikHarfSayisi = 0;
                }
                
            }else{
                jTextField2.setText("");
                //Yanlış harf sayısını arttır ve resmi güncelle.
                yanlisTahmin++;
                score-=3;
                
                if(yanlisTahmin == 11){
                    //Oyunu bitir. Kronometreyi durdur. Oyunlar.txt'ye kaydetme işlemlerini yap.
                    resmiGuncelle(yanlisTahmin);
                    kronometre.stop();
                    sonucYaz(score, gecenSaniye, "Yenilgi");
                    JOptionPane.showMessageDialog(this, "Oyunu kaybettiniz! Kelime: " + hedefKelime);
                    eskiSkorlar();
                }else{
                    resmiGuncelle(yanlisTahmin);
                }
                
            }
            
            
        }else if(!kelime.isEmpty()){
            dogruTahmin = false;
            char[] girilenKelime = kelime.toCharArray();
            
            
            if(kelime.equals(hedefKelime)){
                dogruTahmin = true;
                 
                for(int i = 0; i < hedefKelime.length(); i++){
                
                    
                        JLabel ilgiliEtiket = (JLabel) jPanel4.getComponent(i);

                        ilgiliEtiket.setText(String.valueOf(girilenKelime[i]));

                        dogruTahmin = true;
                        score += 5;
                    
               
                
                }
                      

                        
                jTextField1.setText("");
                //Kazandığı zaman yapılacaklar.
                kronometre.stop();
                sonucYaz(score, gecenSaniye, "Kazanıldı");
                JOptionPane.showMessageDialog(this,"Kazandınız!");
                eskiSkorlar();
            }else{
                //yanlış tahmin yaptığı için fotoğraf değişecek.
                score-=3;
                yanlisTahmin++;
                jTextField1.setText("");
                
                if(yanlisTahmin == 11){
                    //Oyunu bitir. Kronometreyi durdur. Oyunlar.txt'ye kaydetme işlemlerini yap.
                    resmiGuncelle(yanlisTahmin);
                    kronometre.stop();
                    sonucYaz(score, gecenSaniye, "Yenilgi");
                    JOptionPane.showMessageDialog(this, "Oyunu kaybettiniz! Kelime: " + hedefKelime);
                    eskiSkorlar();
                }else{
                    resmiGuncelle(yanlisTahmin);
                }
            }
        }else{
            JOptionPane.showMessageDialog(this,"Lütfen bir harf veya kelime giriniz!");
        }
        jLabel4.setText("Puan: " + score);
        
    }//GEN-LAST:event_jButton1ActionPerformed

